// Softhouse POS voice-over: one ElevenLabs clip per scene so each line syncs with its scene.
// LOCKED settings: eleven_v3, stability 0.42, similarity 0.78, style 0.6, speaker boost.
// Each clip is tightened (atrim+concat) and its duration written to src/softhouse/vo-durations.ts,
// which the composition uses to size every scene around its line.
// Usage: npm run softhouse:voice            (all lines; existing clips are kept)
//        npm run softhouse:voice -- --force (regenerate everything)
import { spawnSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT, elevenlabs, ensureDir, probeDuration, pub, runFfmpeg } from "./_lib.mjs";

const VOICE_ID = "FGY2WhTYpPnrIDTdsKH5"; // Laura — ElevenLabs default voice (works on the free plan)

const LINES = {
  hook: "¿Sigues cobrando con libreta y calculadora?",
  pain: "Errores en el cambio. Inventario a ojo. Productos que caducan. Hay una forma mejor.",
  reveal: "Softhouse POS: el punto de venta multigiro.",
  sell: "Vende rápido y sin errores, con lector de código de barras y precios de mayoreo y granel automáticos.",
  pay: "Cobra en efectivo, tarjeta, transferencia o crédito, calcula el cambio al instante e imprime tu ticket con el IVA desglosado.",
  stock: "Controla tu inventario con alertas de stock mínimo, lotes, caducidades y kárdex.",
  modules: "Caja, clientes, compras, proveedores y reportes: todo tu negocio en un solo lugar.",
  hero: "Escanea. Cobra. Imprime.",
  ctaMl: "Moderniza tu negocio hoy. ¡Cómpralo ya!",
  ctaWa: "Moderniza tu negocio hoy. Solicita tu demo por WhatsApp.",
};

const force = process.argv.includes("--force");
const durations = {};
const starts = {};

/** Sentence start times (s) inside a tightened clip: 0 plus the end of every inter-sentence pause. */
const sentenceStarts = (file) => {
  const { stderr } = runFfmpeg(["-hide_banner", "-i", file, "-af", "silencedetect=noise=-38dB:d=0.12", "-f", "null", "-"]);
  const ends = [...stderr.matchAll(/silence_end:\s*([\d.]+)/g)].map((m) => +(+m[1]).toFixed(3));
  return [0, ...ends.filter((t) => t < probeDuration(file) - 0.1)];
};

for (const [key, text] of Object.entries(LINES)) {
  const raw = pub(`audio/softhouse/vo-${key}-raw.mp3`);
  const out = pub(`audio/softhouse/vo-${key}.mp3`);
  if (!existsSync(out) || force) {
    console.log(`→ ${key}…`);
    const audio = await elevenlabs(`/v1/text-to-speech/${VOICE_ID}?output_format=mp3_44100_128`, {
      text,
      model_id: "eleven_v3",
      voice_settings: { stability: 0.42, similarity_boost: 0.78, style: 0.6, use_speaker_boost: true },
    });
    ensureDir(raw);
    writeFileSync(raw, audio);
    const r = spawnSync(process.execPath, [resolve(ROOT, "scripts/tighten-voice.mjs"), raw, out], { encoding: "utf8" });
    if (r.status !== 0) throw new Error(`tighten failed for ${key}: ${r.stderr}`);
  }
  durations[key] = +probeDuration(out).toFixed(3);
  starts[key] = sentenceStarts(out);
  console.log(`✔ ${key}: ${durations[key]}s`);
}

writeFileSync(
  resolve(ROOT, "src/softhouse/vo-durations.ts"),
  `// Generated by scripts/softhouse-voice.mjs — seconds per tightened voice-over clip,\n// and the start time (s) of each sentence inside it (for syncing staggered visuals).\nexport const VO = ${JSON.stringify(durations, null, 2)} as const;\n\nexport const VO_STARTS: Record<keyof typeof VO, readonly number[]> = ${JSON.stringify(starts, null, 2)};\n`,
);
console.log("✔ src/softhouse/vo-durations.ts");
